/** Look up a key for a language, interpolating {vars}. Falls back to English, then the key. */
export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let str = (CATALOG[lang] && CATALOG[lang][key]) || CATALOG[DEFAULT_LANG][key] || key;
  if (vars) for (const k in vars) str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
  return str;
}

export function normalizeLocale(locale: string | undefined | null): Lang {
  if (!locale) return DEFAULT_LANG;
  const base = locale.toLowerCase().split(/[-_]/)[0];
  return (SUPPORTED_LANGS as string[]).includes(base) ? (base as Lang) : DEFAULT_LANG;
}
